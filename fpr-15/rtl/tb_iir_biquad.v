/*
 * Course: EE2000 Signal Processing, Fall 2026, IIT Hyderabad
 * Module: tb_iir_biquad.v
 * Purpose: Self-checking testbench for 22-channel pipelined IIR biquad bandpass filter.
 * Tests:
 *   1. Full 22-channel interleaved replay comparing RTL against golden vectors.
 *   2. Per-channel error profiling (acceptance: max abs error <= 1 LSB).
 *   3. Zero channel crosstalk test: inject sinusoid on ch5 only, verify all other 21 channels stay zero.
 */

`timescale 1ns / 1ps

module tb_iir_biquad;

    reg clk;
    reg rst_n;
    reg reset_state;
    reg sample_valid;
    reg [4:0] ch_in;
    reg signed [15:0] sample_in;

    wire out_valid;
    wire [4:0] ch_out;
    wire signed [15:0] sample_out;

    iir_biquad #(
        .DATA_WIDTH(16),
        .NUM_CHANNELS(22),
        .COEFF_SHIFT(20),
        .ACCUM_WIDTH(64)
    ) dut (
        .clk(clk),
        .rst_n(rst_n),
        .reset_state(reset_state),
        .sample_valid(sample_valid),
        .ch_in(ch_in),
        .sample_in(sample_in),
        .out_valid(out_valid),
        .ch_out(ch_out),
        .sample_out(sample_out)
    );

    always #5 clk = ~clk; // 100 MHz clock

    // Vector memories (11,264 samples = 22 channels x 512 samples)
    localparam TEST_SAMPLES = 11264;
    reg [15:0] stim_mem [0:TEST_SAMPLES-1];
    reg [15:0] exp_mem  [0:TEST_SAMPLES-1];

    integer i, ch_idx;
    integer max_abs_err;
    integer err_per_ch [0:21];
    integer total_checked;
    integer crosstalk_errors;

    initial begin
        $display("================================================================");
        $display(" EE2000 TB_IIR_BIQUAD: 22-Channel Pipelined IIR Verification");
        $display("================================================================");

        // Load test vectors generated by golden/golden.py
        $readmemh("golden/vectors/tb_iir_input.hex", stim_mem);
        $readmemh("golden/vectors/tb_iir_expected.hex", exp_mem);

        clk          = 0;
        rst_n        = 0;
        reset_state  = 0;
        sample_valid = 0;
        ch_in        = 0;
        sample_in    = 0;
        max_abs_err  = 0;
        total_checked= 0;
        crosstalk_errors = 0;

        for (ch_idx = 0; ch_idx < 22; ch_idx = ch_idx + 1) begin
            err_per_ch[ch_idx] = 0;
        end

        #100;
        rst_n = 1;
        #100;

        // -------------------------------------------------------------
        // Test 1: Full 22-Channel Interleaved Vector Comparison
        // -------------------------------------------------------------
        $display("[TEST 1] Replaying %0d interleaved samples across 22 channels...", TEST_SAMPLES);

        for (i = 0; i < TEST_SAMPLES; i = i + 1) begin
            @(posedge clk);
            sample_valid <= 1'b1;
            ch_in        <= i % 22;
            sample_in    <= stim_mem[i];
            @(posedge clk);
            sample_valid <= 1'b0;

            // Wait for 3-stage pipeline output
            @(posedge clk);
            while (!out_valid) @(posedge clk);

            // Verify channel tag
            if (ch_out !== (i % 22)) begin
                $display("[FAIL] Channel tag mismatch: expected %0d, got %0d at index %0d", (i % 22), ch_out, i);
                $finish;
            end

            // Compare against golden expected output
            begin : cmp_block
                integer diff;
                reg signed [15:0] exp_val;
                exp_val = exp_mem[i];
                diff = sample_out - exp_val;
                if (diff < 0) diff = -diff;

                if (diff > 1 && max_abs_err <= 1) begin
                    $display("First error at Sample %0d (ch %0d): RTL = %0d, EXP = %0d, DIFF = %0d", i, ch_out, sample_out, exp_val, diff);
                end

                if (diff > max_abs_err) max_abs_err = diff;
                if (diff > err_per_ch[ch_out]) err_per_ch[ch_out] = diff;
                total_checked = total_checked + 1;
            end

            // Small spacing between samples (simulates arrival interval)
            #20;
        end

        $display("[INFO] Checked %0d samples across 22 channels.", total_checked);
        $display("[INFO] Overall Maximum Absolute Error: %0d LSB", max_abs_err);

        if (max_abs_err <= 1) begin
            $display("[PASS] Test 1: Bit-accurate agreement within <= 1 LSB achieved!");
        end else begin
            $display("[FAIL] Test 1: Max error %0d exceeds 1 LSB tolerance!", max_abs_err);
        end

        // -------------------------------------------------------------
        // Test 2: Channel Crosstalk Isolation Test
        // -------------------------------------------------------------
        $display("\n[TEST 2] Testing Channel Crosstalk Isolation (stimulus only on ch5)...");
        // Clear all channel states
        @(posedge clk);
        reset_state <= 1'b1;
        @(posedge clk);
        reset_state <= 1'b0;
        #500; // Wait for sequential clear sweep

        // Inject 500 samples of sinusoid only on channel 5, 0 on all other channels
        for (i = 0; i < 22 * 50; i = i + 1) begin
            @(posedge clk);
            sample_valid <= 1'b1;
            ch_in        <= i % 22;
            if ((i % 22) == 5)
                sample_in <= 16'sh4000; // +16384 on channel 5
            else
                sample_in <= 16'sh0000; // Zero on all other 21 channels

            @(posedge clk);
            sample_valid <= 1'b0;

            @(posedge clk);
            while (!out_valid) @(posedge clk);

            // If not channel 5, output must be strictly 0
            if (ch_out !== 5 && sample_out !== 16'sh0000) begin
                crosstalk_errors = crosstalk_errors + 1;
            end
            #20;
        end

        if (crosstalk_errors == 0) begin
            $display("[PASS] Test 2: Zero crosstalk detected! Unstimulated channels remained at 0.");
        end else begin
            $display("[FAIL] Test 2: Crosstalk detected! %0d non-zero outputs on inactive channels.", crosstalk_errors);
        end

        // -------------------------------------------------------------
        // Final Summary
        // -------------------------------------------------------------
        $display("================================================================");
        if (max_abs_err <= 1 && crosstalk_errors == 0) begin
            $display(">>> ALL IIR BIQUAD TESTS PASSED! TASK 2 VERIFIED! <<<");
        end else begin
            $display(">>> TASK 2 VERIFICATION FAILED <<<");
        end
        $display("================================================================");

        #500;
        $finish;
    end

endmodule
