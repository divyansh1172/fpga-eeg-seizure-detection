/*
 * Course: EE2000 Signal Processing, Fall 2026, IIT Hyderabad
 * Module: tb_svm_cosim.v
 * Purpose: Co-simulation testbench for svm_classifier.v.
 *          Drives file-based stimulus from Python into the actual RTL module,
 *          captures cycle-accurate hardware score and decision, and exports
 *          results to cosim_results.hex for bit-exact verification.
 */

`timescale 1ns / 1ps

module tb_svm_cosim;

    parameter FEAT_DIM     = 176;
    parameter FEAT_WIDTH   = 16;
    parameter WEIGHT_WIDTH = 16;
    parameter BIAS_WIDTH   = 32;
    parameter ACCUM_WIDTH  = 40;
    parameter MAX_WINDOWS  = 32;

    reg                          clk;
    reg                          rst_n;
    reg                          start;
    reg  signed [FEAT_WIDTH-1:0]   feat_data;
    reg  signed [WEIGHT_WIDTH-1:0] weight_data;
    reg  signed [BIAS_WIDTH-1:0]   bias_data;

    wire                         done;
    wire                         decision;
    wire signed [ACCUM_WIDTH-1:0] score;

    // Instantiate the actual production RTL module
    svm_classifier #(
        .FEAT_DIM(FEAT_DIM),
        .FEAT_WIDTH(FEAT_WIDTH),
        .WEIGHT_WIDTH(WEIGHT_WIDTH),
        .BIAS_WIDTH(BIAS_WIDTH),
        .ACCUM_WIDTH(ACCUM_WIDTH)
    ) dut (
        .clk(clk),
        .rst_n(rst_n),
        .start(start),
        .feat_data(feat_data),
        .weight_data(weight_data),
        .bias_data(bias_data),
        .done(done),
        .decision(decision),
        .score(score)
    );

    // Clock generation: 100 MHz (10 ns period)
    always #5 clk = ~clk;

    // Stimulus memory buffers
    reg signed [15:0] weight_rom [0:FEAT_DIM-1];
    reg signed [31:0] bias_rom   [0:0];
    reg signed [15:0] feature_rom[0:(MAX_WINDOWS * FEAT_DIM)-1];
    reg [31:0]        control_rom[0:3]; // [0] = num_windows

    integer num_windows;
    integer w_idx;
    integer j;
    integer out_file;

    initial begin
        clk         = 0;
        rst_n       = 0;
        start       = 0;
        feat_data   = 16'sd0;
        weight_data = 16'sd0;
        bias_data   = 32'sd0;

        // Load stimulus files generated by Python
        $readmemh("cosim_weights.hex", weight_rom);
        $readmemh("cosim_bias.hex", bias_rom);
        $readmemh("cosim_features.hex", feature_rom);
        $readmemh("cosim_control.hex", control_rom);

        num_windows = control_rom[0];
        bias_data   = bias_rom[0];

        out_file = $fopen("cosim_results.hex", "w");
        if (out_file == 0) begin
            $display("[ERROR] Could not open cosim_results.hex for writing!");
            $finish;
        end

        // Release reset
        #20;
        @(posedge clk);
        rst_n = 1;
        #20;
        @(posedge clk);

        // Process each window
        for (w_idx = 0; w_idx < num_windows; w_idx = w_idx + 1) begin
            @(posedge clk);
            // Cycle 0: assert start and present feature 0, weight 0
            start       <= 1'b1;
            feat_data   <= feature_rom[w_idx * FEAT_DIM + 0];
            weight_data <= weight_rom[0];

            for (j = 1; j < FEAT_DIM; j = j + 1) begin
                @(posedge clk);
                start       <= 1'b0;
                feat_data   <= feature_rom[w_idx * FEAT_DIM + j];
                weight_data <= weight_rom[j];
            end

            // Wait for done
            @(posedge clk);
            start     <= 1'b0;
            feat_data <= 16'sd0;

            while (!done) begin
                @(posedge clk);
            end

            // Capture hardware score and decision at done
            // 40-bit hex (10 characters) and 1-bit decision
            $fdisplay(out_file, "%010X %0d", score, decision);
            #10;
        end

        $fclose(out_file);
        #50;
        $finish;
    end

endmodule
